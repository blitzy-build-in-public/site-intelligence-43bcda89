/**
 * Production-order seed records: every build order the plant lines carry across the fifteen
 * Monday-to-Friday weeks that straddle the demonstration clock. Records only — nothing here is
 * computed, and only `src/services/mock/seed-loader.ts` may import this folder (rule P-2).
 *
 * Fixing inputs:
 * - AAP 0.12.2 §3 entity table: a production order names one plant, one line, one product and a
 *   planned quantity over a date range. Those eight members, and no others, are what the table
 *   states, so the interface below declares them and nothing more.
 * - AAP 0.2.3 scale table fixes "90 production orders". The table holds exactly ninety: six lines
 *   over fifteen weeks, so the count is a property of the records rather than of a loop.
 * - `platform-contracts.md` §1 fixes identifier patterns for exceptions, customer orders, purchase
 *   orders, scenarios, approvals, audit events, policies, documents, pins, packages, competitors and
 *   chokepoints, but names none for a production order. Inventing a prefix would create an
 *   identifier family the inputs do not define, so `id` is derived from the record's own plant, line
 *   and start date as `<plantId>-<lineId>-<startDate>` instead: one order per line per week makes
 *   that triple unique by construction, the value states nothing the record does not already state,
 *   and it stays stable with no counter, no clock and no random source behind it.
 * - `platform-contracts.md` §1 fixes the demonstration clock at 2026-12-03T08:00:00+01:00 (a
 *   Thursday) and the Monday-to-Friday working calendar, so every order runs Monday to Friday and
 *   `complete`, `running` and `planned` mean the same thing on every run: a week that closed before
 *   the demonstration week is complete, the week containing the clock is running, a later week is
 *   planned. `held` marks an order the line has not closed.
 *
 * Line mapping. `src/seed/plants.ts` is not part of this module's inputs, so the plant -> line ->
 * product assignment is stated here once: PLT-RGB runs LN-RGB-1 (PRD-R75) and LN-RGB-2 (PRD-A200);
 * PLT-BRN runs LN-BRN-1 (PRD-R75) and LN-BRN-2 (PRD-V40); PLT-QRO runs LN-QRO-1 (PRD-A200); PLT-RAK
 * runs LN-RAK-1 (PRD-V40). Each of the three products is therefore built at two lines, which is the
 * "one or two lines" of AAP 0.12.2, and every line builds exactly one product.
 *
 * Rules served: P-6 (every `plannedUnits` figure is record content, and no total, aggregate or
 * expected result is written here), P-7 (synthetic identifiers and figures only), B-1 (no address of
 * any sort) and B-2 (no credential, no environment read).
 */
import type { IsoDate, LineId, PlantId, ProductId } from '../types';

/**
 * One production order: the build a single line carries over one working week.
 *
 * A record, not a result: the planned quantity is stated by the seed and no module recomputes it
 * from the line's rate, the calendar or the week's length.
 */
export interface ProductionOrder {
  /**
   * Identifier derived from the record's own plant, line and start date
   * (`<plantId>-<lineId>-<startDate>`), which is unique because a line carries one order per week.
   */
  id: string;

  /** Plant whose line carries the order. */
  plantId: PlantId;

  /** Line that builds the order; it belongs to `plantId` and builds `productId`. */
  lineId: LineId;

  /** Product the line builds during the order. */
  productId: ProductId;

  /** Units the order plans for the line over its working week, as the seed states them. */
  plannedUnits: number;

  /** First working day of the order, a calendar date in the application's zone. */
  startDate: IsoDate;

  /** Last working day of the order; never before `startDate`. */
  endDate: IsoDate;

  /** Where the order stands: closed before the demonstration week, in it, after it, or held. */
  status: 'planned' | 'running' | 'complete' | 'held';
}

